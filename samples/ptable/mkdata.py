"""mkdata.py elements.csv > elements.inc: the element table as C initialisers for chem.c.

With ELEM_POOL defined it gives the string pool (every text, each once, NUL-terminated), else the elements' rows,
whose texts are 16-bit offsets in that pool: no pointers, so no relocations and half the size.

The CSV has one row per element, z 1 to 118 in order, with the columns
z,sym,name,mass,cat,en,density,density_unit,mp,bp,subl,config. An empty field is a missing value. mass is as shown
("55.845", or "[98]" for an element without a standard atomic weight); temperatures are in degrees C.
Python 3, standard library only.
"""
import csv
import sys
from decimal import Decimal

CATS = ["Alkali metal", "Alkaline earth metal", "Transition metal", "Post-transition metal", "Metalloid",
        "Nonmetal", "Halogen", "Noble gas", "Lanthanide", "Actinide"]
COLUMNS = ["z", "sym", "name", "mass", "cat", "en", "density", "density_unit", "mp", "bp", "subl", "config"]


def place(z):
    """(row, col) in the 18-column table: rows 0-6 the periods, rows 7-8 the lanthanides and actinides under
    groups 3-17 (cols 2-16); group 3 of periods 6 and 7 (col 2) is left for the marker."""
    if z == 1:
        return 0, 0
    if z == 2:
        return 0, 17
    for row, first in ((1, 3), (2, 11)):                     # periods 2 and 3: 2 + 6 elements
        if first <= z < first + 8:
            i = z - first
            return row, i if i < 2 else i + 10
    for row, first in ((3, 19), (4, 37)):                    # periods 4 and 5: all 18
        if first <= z < first + 18:
            return row, z - first
    for row, first in ((5, 55), (6, 87)):                    # periods 6 and 7: 32 each
        if first <= z < first + 32:
            i = z - first
            if i < 2:
                return row, i
            if i < 17:
                return row + 2, i                            # the f row: La..Lu, Ac..Lr at cols 2-16
            return row, i - 14                               # Hf.. at col 3
    raise ValueError(f"no place for z {z}")


def c_str(s):
    if any(ord(ch) < 32 or ord(ch) > 126 for ch in s):
        raise ValueError(f"not plain ASCII: {s!r}")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def mass_e5(text):
    v = Decimal(text.strip("[]"))
    e5 = v * 100000
    if e5 != e5.to_integral_value():
        raise ValueError(f"mass {text} has more than 5 decimals")
    return int(e5)


def main():
    with open(sys.argv[1], newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows or list(rows[0].keys()) != COLUMNS:
        sys.exit("mkdata.py: the columns must be " + ",".join(COLUMNS))
    if [int(r["z"]) for r in rows] != list(range(1, 119)):
        sys.exit("mkdata.py: the rows must be z 1 to 118, in order")
    out = ["/* elements.inc - generated by mkdata.py from elements.csv: do not edit. */",
           "#ifdef ELEM_POOL"]
    pool, offs = [], {}

    def off(s):
        """The offset of s in the string pool, shared with an equal string already there."""
        if s not in offs:
            offs[s] = sum(len(p) + 1 for p in pool)
            pool.append(s)
        return str(offs[s])
    body = []
    for r in rows:
        z = int(r["z"])
        row, col = place(z)
        if r["cat"] not in CATS:
            sys.exit(f"mkdata.py: z {z}: unknown category {r['cat']!r}")
        if r["density_unit"] not in ("g/cm3", "g/L"):
            sys.exit(f"mkdata.py: z {z}: unknown density unit {r['density_unit']!r}")
        fields = [str(z), str(CATS.index(r["cat"])), str(row), str(col), "1" if r["density_unit"] == "g/L" else "0",
                  "1" if r["subl"] == "1" else "0", str(mass_e5(r["mass"]))]
        fields += [off(r[k]) for k in ("sym", "name", "mass", "en", "density", "mp", "bp", "config")]
        body.append("{ " + ", ".join(fields) + " },")
    size = sum(len(p) + 1 for p in pool)
    if size > 65535:
        sys.exit("mkdata.py: the string pool is over 64 KB")
    out += [c_str(p) + ' "\\0"' for p in pool]           # the pool: each string with its NUL
    out += ["#else"] + body
    out.append("#define CAT_NAMES " + ", ".join(c_str(c) for c in CATS))
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
